// Usage: node scripts/build-beginner-sets.js <path to the Java_Notes_Kunal_DSA_PlayList folder>
// Writes question-sets-beginner.js: the Beginner track's DSA question sets, made from the Kunal practice sheet
// (dsa_practice_sheet.md, read from its structured copy web/practice-data.json). One set per sheet section, in the
// sheet's order. Each problem is practised on the Beginner day that teaches its roadmap topic ("2.5", "11.9"…): the
// day whose subtopic label starts with that number in data-beginner.js. The Interview track keeps question-sets.js.
// Run it again after the practice sheet or the Beginner day list changes.
const fs = require("fs");
const path = require("path");
const { root, loadData } = require("./lib");

const source = process.argv[2];
const file = source && path.join(source, "web", "practice-data.json");
if (!file || !fs.existsSync(file)) {
  console.error("Usage: node scripts/build-beginner-sets.js <path to Java_Notes_Kunal_DSA_PlayList>");
  process.exit(1);
}
const sheet = JSON.parse(fs.readFileSync(file, "utf8"));

// Roadmap topic number → Beginner day, from labels like "2.5 Binary search…" or "11.5–11.7 Cycle detection…"
const beginner = loadData().beginner;
const topicDay = {};
beginner.forEach(d => d.topics.forEach(t => t.subtopics.forEach(s => {
  const m = /^(\d+)\.(\d+)(?:–(?:\d+)\.(\d+))?\s/.exec(s.label);
  if (!m) return;
  for (let n = +m[2]; n <= +(m[3] || m[2]); n++) topicDay[`${m[1]}.${n}`] ??= d.day;
})));
// Phase 13 has no topic numbers in the roadmap; the sheet calls string matching 13.1
const kmp = beginner.find(d => d.topics.some(t => t.subtopics.some(s => s.id === "k_d14")));
if (kmp) topicDay["13.1"] = kmp.day;

const ICONS = {
  Foundations: "🌱", "Arrays and hashing": "🧮", Searching: "🔍", "Strings and bits": "🔤", Recursion: "🔁",
  "Linear data structures": "🔗", Greedy: "💰", Trees: "🌳", Heaps: "⛰️", Graphs: "🕸️",
  "Dynamic programming": "🧠", Tries: "🔠"
};
const LC_DIFF = { Easy: "E", Medium: "M", Hard: "H" };
const SHEET_DIFF = { Basic: "E", Core: "M", Pro: "H" };   // the sheet's own level, for problems not on LeetCode

const escape = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const describe = (text) => escape(text).replace(/`([^`]+)`/g, "<code>$1</code>");

const problems = [];
const missing = [];
const sets = sheet.sections.map(section => {
  const items = sheet.problems.filter(p => p.section === section.id);
  const days = new Set();
  const rows = items.map(p => {
    const day = topicDay[p.topic];
    if (day) days.add(day); else missing.push(`${p.slug} (topic ${p.topic})`);
    problems.push(p);
    // [number, title, slug, difficulty, premium, link, statement]: number "" and a link to takeuforward when the
    // problem has no exact LeetCode page; then the slug gets a "tuf-" prefix so it can't clash with a LeetCode one
    return p.lc
      ? [p.lc.n, p.name, p.lc.slug, LC_DIFF[p.lc.diff], p.lc.paid || undefined]
      : ["", p.name, `tuf-${p.slug}`, SHEET_DIFF[p.level] || "M", undefined, p.tuf, p.desc];
  });
  return {
    id: `kunal-${section.id}`,
    name: section.title.replace(/^./, c => c.toUpperCase()),
    icon: ICONS[section.part] || "🧩",
    part: section.part,
    description: describe(section.spot || ""),
    notes: section.notes,
    days: [...days].sort((a, b) => a - b),
    problems: rows
  };
});

if (missing.length) {
  console.error(`No Beginner day teaches the topic of: ${missing.join(", ")}`);
  process.exit(1);
}

const row = (p) => {
  while (p.length && p[p.length - 1] === undefined) p.pop();
  return JSON.stringify(p.map(x => (x === undefined ? null : x)));
};
const out = `// ============================================================
// DSA Question Sets — Beginner track (generated by scripts/build-beginner-sets.js; edit the practice sheet, not this)
// From the Kunal practice sheet (notes/kunal/dsa_practice_sheet.md): one set per section, problems placed on the
// Beginner day that teaches their roadmap topic. Same row format as question-sets.js, plus two optional fields:
//   [number, title, slug, difficulty, premium, link, statement]
// For a problem with no exact LeetCode page the number is "", the slug starts with "tuf-", \`link\` is its page
// on takeuforward and \`statement\` describes the task.
// ============================================================

const BEGINNER_SETS = [
${sets.map(s => `  {
    id: ${JSON.stringify(s.id)},
    name: ${JSON.stringify(s.name)},
    icon: ${JSON.stringify(s.icon)},
    part: ${JSON.stringify(s.part)},
    description: ${JSON.stringify(s.description)},
    notes: ${JSON.stringify(s.notes)},
    days: ${JSON.stringify(s.days)},
    problems: [
${s.problems.map(p => `      ${row([...p])}`).join(",\n")}
    ]
  }`).join(",\n")}
];
`;
fs.writeFileSync(path.join(root, "question-sets-beginner.js"), out);
const onLc = problems.filter(p => p.lc).length;
console.log(`question-sets-beginner.js: ${sets.length} sets, ${problems.length} problems (${onLc} on LeetCode, ${problems.length - onLc} on takeuforward)`);
