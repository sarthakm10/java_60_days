// Usage: node scripts/build-videos.js
// Writes videos.js: the explainer videos, which live as files on the "videos" release of the GitHub repo, not in the
// repo itself. Beginner days are named "Day 7 Title.mp4" or "Day 41A Title.mp4" before upload, Frontend modules
// "Frontend 12 Title.mp4" or "Frontend 29A Title.mp4". GitHub turns spaces and symbols into dots
// ("Day.41A.Title.mp4"), so the number and part are read from the start of the name. The nicer titles come from the
// original files in Videos/ and Videos/Frontend/ when they are on this computer (Videos/ is not committed).
// Run it again after adding videos to the release.
const fs = require("fs");
const path = require("path");

const REPO = "sarthakm10/java_60_days";
const TAG = "videos";
const root = path.join(__dirname, "..");

async function main() {
  const res = await fetch(`https://api.github.com/repos/${REPO}/releases/tags/${TAG}`, {
    headers: { Accept: "application/vnd.github+json", "User-Agent": "build-videos-script" }
  });
  if (!res.ok) throw new Error(`GitHub answered ${res.status} for the "${TAG}" release`);
  const assets = (await res.json()).assets.filter(a => /\.mp4$/i.test(a.name));

  // Titles from the original file names: "Day 41A Linked Lists.mp4" → { "41A": "Linked Lists" }
  const KINDS = { Day: "Videos", Frontend: path.join("Videos", "Frontend") };
  const local = { Day: {}, Frontend: {} };
  for (const [kind, dir] of Object.entries(KINDS)) {
    const full = path.join(root, dir);
    if (!fs.existsSync(full)) continue;
    for (const f of fs.readdirSync(full)) {
      const m = new RegExp(`^${kind} (\\d+)([A-Za-z]?) (.+)\\.mp4$`, "i").exec(f);
      if (m) local[kind][`${+m[1]}${m[2].toUpperCase()}`] = m[3].trim();
    }
  }

  const found = { Day: {}, Frontend: {} };
  const skipped = [];
  for (const a of assets) {
    const m = /^(Day|Frontend)\.(\d+)([A-Za-z]?)\.(.+)\.mp4$/i.exec(a.name);
    if (!m) { skipped.push(a.name); continue; }
    const kind = m[1][0].toUpperCase() + m[1].slice(1).toLowerCase();
    const num = +m[2];
    const part = m[3].toUpperCase();
    const title = local[kind][`${num}${part}`] || m[4].replace(/\./g, " ").replace(/\s+/g, " ").trim();
    (found[kind][num] ||= []).push({ part, title, file: a.name, mb: Math.round(a.size / 1048576) });
  }
  const listing = (byNum) => {
    Object.values(byNum).forEach(list => list.sort((x, y) => x.part.localeCompare(y.part)));
    return Object.keys(byNum).map(Number).sort((a, b) => a - b)
      .map(n => `  ${n}: [\n${byNum[n].map(v => `    ${JSON.stringify(v)}`).join(",\n")}\n  ]`).join(",\n");
  };
  const days = found.Day, modules = found.Frontend;
  const sorted = Object.keys(days).map(Number).sort((a, b) => a - b);
  const moduleNums = Object.keys(modules).map(Number).sort((a, b) => a - b);
  const out = `// ============================================================
// Explainer videos (generated by scripts/build-videos.js; don't edit by hand)
// Streamed from the "${TAG}" release on GitHub (they are not in the repo).
// DAY_VIDEOS: Beginner day → videos · FRONTEND_VIDEOS: Frontend module → videos (both tracks)
// Each video: { part ("" or "A", "B"…), title, file (the release file name), mb }
// ============================================================

const VIDEO_BASE = "https://github.com/${REPO}/releases/download/${TAG}/";

const DAY_VIDEOS = {
${listing(days)}
};

const FRONTEND_VIDEOS = {
${listing(modules)}
};
`;
  fs.writeFileSync(path.join(root, "videos.js"), out);
  const count = (byNum) => Object.values(byNum).reduce((n, list) => n + list.length, 0);
  console.log(`videos.js: ${count(days)} videos on ${sorted.length} days (days ${sorted[0]}–${sorted.at(-1)})`);
  console.log(`           ${count(modules)} videos on ${moduleNums.length} frontend modules (modules ${moduleNums[0]}–${moduleNums.at(-1)})`);
  if (skipped.length) console.log(`Skipped (name doesn't start with "Day.N" or "Frontend.N"): ${skipped.join(", ")}`);
}

main().catch(err => { console.error(err.message); process.exit(1); });
