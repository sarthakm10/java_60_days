// Usage: node scripts/build-videos.js
// Writes videos.js: the explainer videos, which live as files on the "videos" release of the GitHub repo, not in the
// repo itself. Beginner days are named "Day 7 Title.mp4" or "Day 41A Title.mp4" before upload, Frontend modules
// "Frontend 12 Title.mp4" or "Frontend 29A Title.mp4". GitHub turns spaces and symbols into dots
// ("Day.41A.Title.mp4"), so the number and part are read from the start of the name. The nicer titles come from the
// original files in Videos/ and Videos/Frontend/ when they are on this computer (Videos/ is not committed).
// Concept videos (from the video-pipeline repo) are named "DSA Sliding Window.mp4", "Java Multithreading and Concurrency
// (Part 1).mp4" or "Spring Core IoC, Dependency Injection and Beans.mp4": each is matched to the Kunal note (in
// data-beginner.js) whose file name shares the most words with it, and shows on the Beginner days that use that note.
// Run it again after adding videos to the release (video-pipeline's upload runs do this on GitHub Actions).
const fs = require("fs");
const path = require("path");

const REPO = "sarthakm10/java_60_days";
const TAG = "videos";
const root = path.join(__dirname, "..");

async function main() {
  // Unauthenticated calls from shared CI runners hit the rate limit (403), so use a token when given
  const token = process.env.GH_TOKEN || process.env.GITHUB_TOKEN;
  const res = await fetch(`https://api.github.com/repos/${REPO}/releases/tags/${TAG}`, {
    headers: { Accept: "application/vnd.github+json", "User-Agent": "build-videos-script",
               ...(token && { Authorization: `Bearer ${token}` }) }
  });
  if (!res.ok) throw new Error(`GitHub answered ${res.status} for the "${TAG}" release`);
  const assets = (await res.json()).assets.filter(a => /\.mp4$/i.test(a.name));

  // Titles from the original file names: "Day 41A Linked Lists.mp4" → { "41A": "Linked Lists" }
  const KINDS = { Day: "Videos", Frontend: path.join("Videos", "Frontend") };
  const local = { Day: {}, Frontend: {} };
  for (const [kind, dir] of Object.entries(KINDS)) {
    const full = path.join(root, dir);
    if (!fs.existsSync(full)) continue;
    for (const f of fs.readdirSync(full)) {
      const m = new RegExp(`^${kind} (\\d+)([A-Za-z]?) (.+)\\.mp4$`, "i").exec(f);
      if (m) local[kind][`${+m[1]}${m[2].toUpperCase()}`] = m[3].trim();
    }
  }

  // Without Videos/ (e.g. on GitHub Actions), keep the titles the current videos.js already has
  const prev = {};
  const old = path.join(root, "videos.js");
  if (fs.existsSync(old)) {
    for (const line of fs.readFileSync(old, "utf8").split("\n")) {
      const t = line.trim().replace(/,$/, "");
      if (!t.startsWith("{\"part\"")) continue;
      try { const v = JSON.parse(t); prev[v.file] = v.title; } catch {}
    }
  }

  const found = { Day: {}, Frontend: {} };
  const skipped = [];
  const concepts = {};
  const conceptLog = [];
  for (const a of assets) {
    if (/^(DSA|Java|Spring)\./i.test(a.name)) {
      const c = conceptVideo(a, prev);
      if (c.note) { (concepts[c.note] ||= []).push(c.video); conceptLog.push(`${a.name} → ${c.note}`); }
      else skipped.push(`${a.name} (${c.why})`);
      continue;
    }
    const m = /^(Day|Frontend)\.(\d+)([A-Za-z]?)\.(.+)\.mp4$/i.exec(a.name);
    if (!m) { skipped.push(a.name); continue; }
    const kind = m[1][0].toUpperCase() + m[1].slice(1).toLowerCase();
    const num = +m[2];
    const part = m[3].toUpperCase();
    const title = local[kind][`${num}${part}`] || prev[a.name] || m[4].replace(/\./g, " ").replace(/\s+/g, " ").trim();
    (found[kind][num] ||= []).push({ part, title, file: a.name, mb: Math.round(a.size / 1048576) });
  }
  const listing = (byNum) => {
    Object.values(byNum).forEach(list => list.sort((x, y) => x.part.localeCompare(y.part)));
    return Object.keys(byNum).map(Number).sort((a, b) => a - b)
      .map(n => `  ${n}: [\n${byNum[n].map(v => `    ${JSON.stringify(v)}`).join(",\n")}\n  ]`).join(",\n");
  };
  const days = found.Day, modules = found.Frontend;
  Object.values(concepts).forEach(list => list.sort((x, y) => x.part.localeCompare(y.part, undefined, { numeric: true })));
  const conceptListing = Object.keys(concepts).sort()
    .map(note => `  ${JSON.stringify(note)}: [\n${concepts[note].map(v => `    ${JSON.stringify(v)}`).join(",\n")}\n  ]`).join(",\n");
  const sorted = Object.keys(days).map(Number).sort((a, b) => a - b);
  const moduleNums = Object.keys(modules).map(Number).sort((a, b) => a - b);
  const out = `// ============================================================
// Explainer videos (generated by scripts/build-videos.js; don't edit by hand)
// Streamed from the "${TAG}" release on GitHub (they are not in the repo).
// DAY_VIDEOS: Beginner day → videos · FRONTEND_VIDEOS: Frontend module → videos (both tracks)
// CONCEPT_VIDEOS: Kunal note file → concept videos (shown on the Beginner days that use the note)
// Each video: { part ("" or "A", "B"…; "1", "2"… for concept parts), title, file (the release file name), mb }
// ============================================================

const VIDEO_BASE = "https://github.com/${REPO}/releases/download/${TAG}/";

const DAY_VIDEOS = {
${listing(days)}
};

const FRONTEND_VIDEOS = {
${listing(modules)}
};

const CONCEPT_VIDEOS = {
${conceptListing}
};
`;
  fs.writeFileSync(path.join(root, "videos.js"), out);
  const count = (byNum) => Object.values(byNum).reduce((n, list) => n + list.length, 0);
  console.log(`videos.js: ${count(days)} videos on ${sorted.length} days (days ${sorted[0]}–${sorted.at(-1)})`);
  console.log(`           ${count(modules)} videos on ${moduleNums.length} frontend modules (modules ${moduleNums[0]}–${moduleNums.at(-1)})`);
  console.log(`           ${conceptLog.length} concept videos on ${Object.keys(concepts).length} Kunal notes`);
  conceptLog.forEach(line => console.log(`             ${line}`));
  if (skipped.length) console.log(`Skipped: ${skipped.join(", ")}`);
}

// ── Concept videos ──
const CONCEPT_FOLDERS = { dsa: "DSA Topics Not Covered Notes/", java: "Java Topics Not Covered Notes/", spring: "Spring Boot Notes/" };
const STOP = new Set(["and", "the", "of", "in", "a", "an", "to", "with", "part", "vs", "md", "mp4", "gap", "topic"]);
const words = (s) => s.toLowerCase().split(/[^a-z0-9]+/).filter(w => w && !STOP.has(w) && !/^\d+$/.test(w));
let kunalNotes;
function notesIn(folder) {
  kunalNotes ||= [...fs.readFileSync(path.join(root, "data-beginner.js"), "utf8").matchAll(/"([^"]+\.md)"/g)].map(m => m[1]);
  return [...new Set(kunalNotes.filter(f => f.startsWith(folder) && !/README/i.test(f)))];
}
// "Java.Multithreading.and.Concurrency.Part.1.mp4" → { note, video: { part: "1", title, file, mb } }
function conceptVideo(a, prev) {
  const [, kind, rest] = /^(DSA|Java|Spring)\.(.+)\.mp4$/i.exec(a.name);
  const partMatch = /\.Part\.(\d+)$/i.exec(rest);
  const part = partMatch ? partMatch[1] : "";
  const base = partMatch ? rest.slice(0, partMatch.index) : rest;
  const vw = new Set(words(base));
  const scored = notesIn(CONCEPT_FOLDERS[kind.toLowerCase()])
    .map(note => ({ note, score: words(path.basename(note).replace(/^[a-z]+_(gap_|topic_)?\d+_/, "")).filter(w => vw.has(w)).length }))
    .sort((x, y) => y.score - x.score);
  if (!scored.length || !scored[0].score) return { why: "no matching Kunal note" };
  if (scored[1] && scored[1].score === scored[0].score) return { why: `matches ${scored[0].note} and ${scored[1].note} equally` };
  const title = conceptTitles()[a.name.toLowerCase()] || prev[a.name] || `${kind} ${base.replace(/\./g, " ")}`;
  return { note: scored[0].note, video: { part, title, file: a.name, mb: Math.round(a.size / 1048576) } };
}
// Nicer titles from Videos/Concepts when it is on this computer: "Spring Core IoC, Dependency Injection and Beans"
let conceptTitleMap;
function conceptTitles() {
  if (conceptTitleMap) return conceptTitleMap;
  conceptTitleMap = {};
  const dir = path.join(root, "Videos", "Concepts");
  if (fs.existsSync(dir)) {
    for (const f of fs.readdirSync(dir)) {
      const m = /^(DSA|Java|Spring) (.+?)(?: \(Part \d+\))?\.mp4$/i.exec(f);
      if (m) conceptTitleMap[f.replace(/[^A-Za-z0-9+_-]+/g, ".").toLowerCase()] = `${m[1]} ${m[2].trim()}`;
    }
  }
  return conceptTitleMap;
}

main().catch(err => { console.error(err.message); process.exit(1); });
