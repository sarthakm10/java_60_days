// Usage: node scripts/build-videos.js
// Writes videos.js: the Beginner track's explainer videos (made with NotebookLM from each day's notes), which live as
// files on the "videos" release of the GitHub repo, not in the repo itself. Each file is named "Day 7 Title.mp4" or
// "Day 41A Title.mp4" before upload; GitHub turns spaces and symbols into dots ("Day.41A.Title.mp4"), so the day and
// part are read from the start of the name. The nicer titles come from the original files in Videos/ when they are
// on this computer (Videos/ is not committed). Run it again after adding videos to the release.
const fs = require("fs");
const path = require("path");

const REPO = "sarthakm10/java_60_days";
const TAG = "videos";
const root = path.join(__dirname, "..");

async function main() {
  const res = await fetch(`https://api.github.com/repos/${REPO}/releases/tags/${TAG}`, {
    headers: { Accept: "application/vnd.github+json", "User-Agent": "build-videos-script" }
  });
  if (!res.ok) throw new Error(`GitHub answered ${res.status} for the "${TAG}" release`);
  const assets = (await res.json()).assets.filter(a => /\.mp4$/i.test(a.name));

  // Titles from the original file names: "Day 41A Linked Lists.mp4" → { "41A": "Linked Lists" }
  const local = {};
  const videosDir = path.join(root, "Videos");
  if (fs.existsSync(videosDir)) {
    for (const f of fs.readdirSync(videosDir)) {
      const m = /^Day (\d+)([A-Za-z]?) (.+)\.mp4$/i.exec(f);
      if (m) local[`${+m[1]}${m[2].toUpperCase()}`] = m[3].trim();
    }
  }

  const days = {};
  const skipped = [];
  for (const a of assets) {
    const m = /^Day\.(\d+)([A-Za-z]?)\.(.+)\.mp4$/i.exec(a.name);
    if (!m) { skipped.push(a.name); continue; }
    const day = +m[1];
    const part = m[2].toUpperCase();
    const title = local[`${day}${part}`] || m[3].replace(/\./g, " ").replace(/\s+/g, " ").trim();
    (days[day] ||= []).push({ part, title, file: a.name, mb: Math.round(a.size / 1048576) });
  }
  Object.values(days).forEach(list => list.sort((x, y) => x.part.localeCompare(y.part)));

  const sorted = Object.keys(days).map(Number).sort((a, b) => a - b);
  const out = `// ============================================================
// Explainer videos — Beginner track (generated by scripts/build-videos.js; don't edit by hand)
// One or more NotebookLM videos per day, streamed from the "${TAG}" release on GitHub (they are not in the repo).
// day → [{ part ("" or "A", "B"…), title, file (the release file name), mb }]
// ============================================================

const VIDEO_BASE = "https://github.com/${REPO}/releases/download/${TAG}/";

const DAY_VIDEOS = {
${sorted.map(d => `  ${d}: [\n${days[d].map(v => `    ${JSON.stringify(v)}`).join(",\n")}\n  ]`).join(",\n")}
};
`;
  fs.writeFileSync(path.join(root, "videos.js"), out);
  console.log(`videos.js: ${assets.length - skipped.length} videos on ${sorted.length} days (days ${sorted[0]}–${sorted.at(-1)})`);
  if (skipped.length) console.log(`Skipped (name doesn't start with "Day.N"): ${skipped.join(", ")}`);
}

main().catch(err => { console.error(err.message); process.exit(1); });
